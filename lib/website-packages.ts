export type WebsiteQuote = { monthly: number; dueNow: number; yearlySaving: number; loyaltyLater: number };

/** Kwoty dla wyboru w cenniku (pkg = null: bez strony); null dla strony na zamówienie.
 *  Stworzenie strony nic nie kosztuje — strona działa, dopóki lokal opłaca abonament. */
export function quote(pkg: WebsitePackage | null, billing: WebsiteBilling, loyalty = false): WebsiteQuote | null {
  const p = pkg ? WEBSITE_PACKAGES.find(x => x.id === pkg)?.monthly : { yearly: 0, monthly: 0 };
  if (!p) return null;
  const monthly = p[billing];
  return {
    monthly,
    dueNow: billing === 'yearly' ? 12 * monthly : monthly,
    yearlySaving: 12 * (p.monthly - p.yearly),
    // Dopłata za pieczątki po darmowym roku; w pakiecie `includedIn` nie ma jej wcale.
    loyaltyLater: loyalty && pkg !== LOYALTY.includedIn ? LOYALTY.monthly : 0,
  };
}

/** Adres strony z nazwy lokalu: małe litery, bez polskich znaków, słowa łączone myślnikiem. */
export function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/ł/g, 'l')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40)
    .replace(/-+$/, '');
}

/** Adres w trakcie pisania: to samo co slugify, ale zostawia myślnik na końcu, żeby dało się pisać dalej. */
export function slugTyping(value: string): string {
  const s = value
    .toLowerCase()
    .replace(/ł/g, 'l')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+/, '')
    .slice(0, 40);
  return s;
}

/** To samo, co sprawdza baza (website_requests.slug). */
export const isValidSlug = (s: string) =>
  /^[a-z0-9]+(-[a-z0-9]+)*$/.test(s) && s.length >= 3 && s.length <= 40 && !RESERVED_SLUGS.includes(s);

