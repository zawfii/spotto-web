// Strona dla lokalu — pakiety i ceny (netto). Prośba trafia do tabeli website_requests.

export type WebsitePackage = 'wizytowka' | 'plus' | 'custom';
export type WebsiteBilling = 'yearly' | 'monthly';

export const WEBSITE_PACKAGES: {
  id: WebsitePackage;
  label: string;
  monthly: { yearly: number; monthly: number } | null; // null = wycena indywidualna
  features: string[];
}[] = [
  {
    id: 'wizytowka',
    label: 'Wizytówka',
    monthly: { yearly: 59, monthly: 79 },
    features: ['Jedna strona pod spootme.pl/twoj-lokal', 'Menu, godziny i zdjęcia ze Spoot', 'Mapa, telefon, dojazd', 'Kod QR do menu'],
  },
  {
    id: 'plus',
    label: 'Strona Plus',
    monthly: { yearly: 99, monthly: 129 },
    features: ['Wszystko z Wizytówki', 'Do 5 podstron: o nas, galeria, catering', 'Oceny gości i aktualne oferty ze Spoot', 'Wersja po angielsku', 'Jedna poprawka w miesiącu'],
  },
  {
    id: 'custom',
    label: 'Strona na zamówienie',
    monthly: null,
    features: ['Projekt od zera pod Twój lokal', 'Blog i aktualności', 'Dowolna liczba podstron', 'Własna domena'],
  },
];

/** Opłata za stworzenie strony: taniej przy 12 miesiącach płatnych z góry. */
export const SETUP_FEE: Record<WebsiteBilling, number> = { yearly: 150, monthly: 500 };

export type WebsiteQuote = { setup: number; monthly: number; dueNow: number; firstYear: number; yearlySaving: number };

/** Kwoty dla pakietu z ceną; null dla strony na zamówienie. */
export function quote(pkg: WebsitePackage, billing: WebsiteBilling): WebsiteQuote | null {
  const p = WEBSITE_PACKAGES.find(x => x.id === pkg)?.monthly;
  if (!p) return null;
  const setup = SETUP_FEE[billing];
  const monthly = p[billing];
  const firstYear = setup + 12 * monthly;
  const monthlyFirstYear = SETUP_FEE.monthly + 12 * p.monthly;
  const yearlyFirstYear = SETUP_FEE.yearly + 12 * p.yearly;
  return {
    setup,
    monthly,
    dueNow: billing === 'yearly' ? firstYear : setup + monthly,
    firstYear,
    yearlySaving: monthlyFirstYear - yearlyFirstYear,
  };
}

/** „1 338 zł” — spacja jako separator tysięcy. */
export const zl = (n: number) => `${String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} zł`;

/** Adres strony z nazwy lokalu: małe litery, bez polskich znaków, słowa łączone myślnikiem. */
export function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/ł/g, 'l')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40)
    .replace(/-+$/, '');
}

/** To samo, co sprawdza baza (website_requests.slug). */
export const isValidSlug = (s: string) => /^[a-z0-9]+(-[a-z0-9]+)*$/.test(s) && s.length >= 3 && s.length <= 40;
