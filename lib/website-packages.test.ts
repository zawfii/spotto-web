// Uruchom: node lib/website-packages.test.ts
import assert from 'node:assert/strict';
import { isValidSlug, quote, slugify, slugTyping, zl } from './website-packages.ts';

assert.deepEqual(quote('wizytowka', 'yearly'), { setup: 150, monthly: 59, dueNow: 858, firstYear: 858, yearlySaving: 590 });
assert.deepEqual(quote('plus', 'yearly'), { setup: 150, monthly: 99, dueNow: 1338, firstYear: 1338, yearlySaving: 710 });
assert.equal(quote('wizytowka', 'monthly')?.dueNow, 579);
assert.equal(quote('plus', 'monthly')?.dueNow, 629);
assert.equal(quote('plus', 'monthly')?.firstYear, 2048);
assert.equal(quote('custom', 'yearly'), null);

assert.equal(zl(1338), '1 338 zł');
assert.equal(zl(59), '59 zł');

assert.equal(slugify('Bistro Zielnik'), 'bistro-zielnik');
assert.equal(slugify('Żółta Łódź & Ćma!'), 'zolta-lodz-cma');
assert.equal(slugify('  --Kawa--  '), 'kawa');
assert.ok(slugify('a'.repeat(60)).length <= 40);
assert.ok(isValidSlug('bistro-zielnik'));
assert.ok(!isValidSlug('ab'));
assert.ok(!isValidSlug('bistro--zielnik'));
assert.ok(!isValidSlug('Bistro'));

assert.equal(slugTyping('Żółta Łódź & Ćma!'), 'zolta-lodz-cma-');
assert.equal(slugTyping('bistro '), 'bistro-');
assert.equal(slugTyping('--@Kawa'), 'kawa');
assert.ok(isValidSlug(slugify(slugTyping('Pod Aniołami #1'))));

console.log('website-packages: ok');
