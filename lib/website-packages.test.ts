// Uruchom: node lib/website-packages.test.ts
import assert from 'node:assert/strict';
import { LOYALTY_NOTE, isValidSlug, quote, slugify, slugTyping, zl } from './website-packages.ts';

assert.deepEqual(quote('wizytowka', 'yearly'), { monthly: 59, dueNow: 708, yearlySaving: 240, loyaltyLater: 0 });
assert.deepEqual(quote('plus', 'yearly'), { monthly: 99, dueNow: 1188, yearlySaving: 360, loyaltyLater: 0 });
assert.equal(quote('wizytowka', 'monthly')?.dueNow, 79); // bez opłaty za stworzenie strony
assert.equal(quote('plus', 'monthly')?.dueNow, 129);
assert.equal(quote('custom', 'yearly'), null);
// Pieczątki: +39 zł po darmowym roku, w Stronie Plus w cenie, bez strony też się liczą.
assert.equal(quote('wizytowka', 'yearly', true)?.loyaltyLater, 39);
assert.equal(quote('plus', 'yearly', true)?.loyaltyLater, 0);
assert.deepEqual(quote(null, 'monthly', true), { monthly: 0, dueNow: 0, yearlySaving: 0, loyaltyLater: 39 });
assert.ok(LOYALTY_NOTE.includes('39 zł netto'));

assert.equal(zl(1338), '1 338 zł');
assert.equal(zl(59), '59 zł');

assert.equal(slugify('Bistro Zielnik'), 'bistro-zielnik');
assert.equal(slugify('Żółta Łódź & Ćma!'), 'zolta-lodz-cma');
assert.equal(slugify('  --Kawa--  '), 'kawa');
assert.ok(slugify('a'.repeat(60)).length <= 40);
assert.ok(isValidSlug('bistro-zielnik'));
assert.ok(!isValidSlug('ab'));
assert.ok(!isValidSlug('bistro--zielnik'));
assert.ok(!isValidSlug('Bistro'));
assert.ok(!isValidSlug('owner')); // zajęte przez trasę spootme.pl/owner
assert.ok(isValidSlug('bistropokazowe'));

assert.equal(slugTyping('Żółta Łódź & Ćma!'), 'zolta-lodz-cma-');
assert.equal(slugTyping('bistro '), 'bistro-');
assert.equal(slugTyping('--@Kawa'), 'kawa');
assert.ok(isValidSlug(slugify(slugTyping('Pod Aniołami #1'))));

console.log('website-packages: ok');
